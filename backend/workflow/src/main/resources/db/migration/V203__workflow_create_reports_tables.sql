CREATE TABLE IF NOT EXISTS REPORT_SALES_MONTHLY (
    report_id INT PRIMARY KEY AUTO_INCREMENT,
    client_id INT,
    month INT NOT NULL,
    year INT NOT NULL,
    total_orders INT NOT NULL DEFAULT 0,
    total_revenue DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (client_id) REFERENCES CLIENT(client_id)
);

CREATE TABLE IF NOT EXISTS REPORT_INVENTORY_MONTHLY (
    report_id INT PRIMARY KEY AUTO_INCREMENT,
    client_id INT,
    month INT NOT NULL,
    year INT NOT NULL,
    stock_added INT NOT NULL DEFAULT 0,
    stock_sold INT NOT NULL DEFAULT 0,
    current_stock INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (client_id) REFERENCES CLIENT(client_id)
);

CREATE TABLE IF NOT EXISTS REPORT_HISTORICAL (
    historical_id INT PRIMARY KEY AUTO_INCREMENT,
    client_id INT,
    month INT,
    year INT,
    metric_type VARCHAR(50) NOT NULL,
    metric_value DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    recorded_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    FOREIGN KEY (client_id) REFERENCES CLIENT(client_id)
);

CREATE TABLE IF NOT EXISTS DASHBOARD_SUMMARY (
    summary_id INT PRIMARY KEY AUTO_INCREMENT,
    client_id INT,
    date DATE NOT NULL,
    total_sales DECIMAL(10,2) NOT NULL DEFAULT 0.00,
    total_orders INT NOT NULL DEFAULT 0,
    low_stock_items INT NOT NULL DEFAULT 0,
    pending_tasks INT NOT NULL DEFAULT 0,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    FOREIGN KEY (client_id) REFERENCES CLIENT(client_id)
);